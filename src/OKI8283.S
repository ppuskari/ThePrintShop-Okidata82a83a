* THE PRINT SHOP V2 - OKIDATA 82A/83A OKIGRAPH I
*
* R9 HARDWARE-VALIDATION BUILD
*
* R9 keeps the proven R8 control/state fixes and adds vertical source-row
* resampling for monochrome type-5 greeting-card pieces.
*
* Firmware-backed geometry:
*
*   Print Shop nominal band pitch = 14/144 inch
*   OkiGraph native band feed     = 15/144 inch
*
* After R8 removed the accidental first-row feed, one monochrome card piece
* still contains 28 seven-row source bands.  The native 15/144-inch advance
* therefore makes the piece about 7.1% too tall.
*
* R9 changes only PRTYPE=5 ($95F1) monochrome card sides 0/1:
*
*   historical source = 28 * 7 = 196 source rows
*   R9 output         = 26 * 7 = 182 output rows
*
* The resampler does NOT drop two complete seven-row bands.  It preserves
* source row 0 and source row 195 and distributes fourteen single-row skips
* through the piece.  Output-band source starts are generated by advancing
* either seven or eight source rows between bands; fourteen of the twenty-five
* transitions advance by eight.
*
* The final output band begins at source row 189 and therefore consumes source
* rows 189..195.  Top and bottom artwork remain represented.
*
* Other printer types are gated out with the shared printer-type byte at $95F1.
* SIDE=2 full-page signs retain their historical row count and stepping.
*
* R8 piece-boundary behavior remains:
*
*   - first outside-card raster starts at the physical head baseline;
*   - later DUMP boundaries use one native graphics feed;
*   - continuous graphics uses $03,$0E between bands;
*   - legacy ML92/93 ESC '%' '9' is never emitted;
*   - LF36 remains suppressed rather than becoming a full 1/6-inch feed.
*
* R9 executable overlays:
*
*   PRCOMS.OKI  2034 bytes
*   MENUS7.OKI  3018 bytes
*   GCDRAW.OKI  2809 bytes (installed as runtime DRAW1)
*
* DRAW1 load address remains $7800.  2809 payload bytes fit the existing DOS
* allocation and stay below the $8300 application-data boundary.
